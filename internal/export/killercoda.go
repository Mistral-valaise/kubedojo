const waitScript = `#!/bin/bash
# Shown to the learner while the background setup runs.
echo "Preparing the task ..."
until [ -f /tmp/.kubedojo-ready ]; do sleep 1; done
clear
echo "Ready. Read the task on the left."
`

// Killercoda writes one scenario per exportable question below dir.
func Killercoda(cat *catalog.Catalog, dir, onlyTrack, sourceURL string) (*Result, error) {
	res := &Result{}
	for _, t := range cat.List() {
		if onlyTrack != "" && t.ID != onlyTrack {
			continue
		}
		for _, q := range t.Questions {
			workers := 0
			if env := t.Environments[q.Environment]; env != nil {
				workers = env.Workers
			}
			if why := reason(q, workers); why != "" {
				res.Skipped = append(res.Skipped, Skipped{t.ID, q.ID, why})
				continue
			}
			out := filepath.Join(dir, t.ID, q.ID)
			if err := os.MkdirAll(out, 0o755); err != nil {
				return nil, err
			}
			d := t.DomainByID(q.Domain)
			var ix index
			ix.Title = fmt.Sprintf("%s | %s", t.Short, q.Title)
			ix.Description = fmt.Sprintf("%s · %s · about %d minutes", d.Title, q.Difficulty, q.Minutes)
			ix.Details.Intro = page{Text: "intro.md", Background: "setup.sh", Foreground: "wait.sh"}
			ix.Details.Steps = []step{{Title: q.Title, Text: "task.md", Verify: "verify.sh"}}
			ix.Details.Finish = page{Text: "finish.md"}
			ix.Backend.ImageID = "kubernetes-kubeadm-2nodes"
			raw, _ := json.MarshalIndent(ix, "", "  ")

			intro := fmt.Sprintf("# %s\n\n**%s — %s** · %s · about %d minutes\n\nThis is an exam-style task: no step-by-step guidance. Solve it in the terminal, then press **CHECK**.\n\nThe cluster has a control plane `controlplane` and a worker `node01`.\n\n> From [kubedojo](%s), an open-source trainer for the CKA and CKS exams with lessons, hints, timed exam simulations and per-check feedback.\n",
				q.Title, t.Short, d.Title, q.Difficulty, q.Minutes, sourceURL)
			hints := ""
			for i, h := range q.Hints {
				hints += fmt.Sprintf("\n<details><summary>Hint %d</summary>\n\n%s\n</details>\n", i+1, strings.TrimSpace(text(h)))
			}
			finish := fmt.Sprintf("# Solved\n\n%s\n---\n\nWant more? [kubedojo](%s) has %d questions like this, timed exam simulations and feedback for every check.\n", text(q.SolutionMd), sourceURL, countAll(cat))
			files := map[string]string{
				"index.json": string(raw) + "\n",
				"intro.md":   intro,
				"task.md":    text(q.Task) + hints,
				"finish.md":  finish,
				"setup.sh":   setupHead + script(q.Setup) + "\n) >/tmp/kubedojo-setup.log 2>&1\ntouch /tmp/.kubedojo-ready\n",
				"wait.sh":    waitScript,
				"verify.sh":  verify(q),
			}
			for name, body := range files {
				mode := os.FileMode(0o644)
				if strings.HasSuffix(name, ".sh") {
					mode = 0o755
				}
				if err := os.WriteFile(filepath.Join(out, name), []byte(body), mode); err != nil {
					return nil, err
				}
			}
			res.Exported = append(res.Exported, t.ID+"/"+q.ID)
		}
	}
	readme := fmt.Sprintf("# kubedojo scenarios for Killercoda\n\nGenerated with `kubedojo content export --format killercoda` from %s.\n\nAdd this directory as a repository to your Killercoda creator profile. Each sub-directory is one scenario.\n\nThese scenarios are generated from questions that are verified on kubedojo's own clusters. They have **not** been run on Killercoda by the generator — try each one there before publishing.\n\n%d scenarios exported, %d questions skipped.\n", sourceURL, len(res.Exported), len(res.Skipped))
	if err := os.WriteFile(filepath.Join(dir, "README.md"), []byte(readme), 0o644); err != nil {
		return nil, err
	}
	return res, nil
}

func countAll(cat *catalog.Catalog) int {
	n := 0
	for _, t := range cat.List() {
		n += len(t.Questions)
	}
	return n
}
