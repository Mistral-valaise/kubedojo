// Package export converts kubedojo questions into other platforms' formats.
//
// The Killercoda export turns each question into a scenario: the setup script
// becomes the intro's background script, the checks become one verify.sh, the
// worked solution becomes the finish page. Killercoda environments have one
// control plane ("controlplane") and at most one worker ("node01"), so
// questions that need more, or that depend on how kubedojo's own nodes are
// built, are skipped and reported.
package export

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/Mistral-valaise/kubedojo/internal/catalog"
	"github.com/Mistral-valaise/kubedojo/internal/checker"
)

// Skipped explains why a question was not exported.
type Skipped struct {
	Track, Question, Reason string
}

// Result summarises an export run.
type Result struct {
	Exported []string
	Skipped  []Skipped
}

// reason returns why q cannot run on Killercoda, or "".
func reason(q *catalog.Question, workers int) string {
	all := q.Task + q.Setup + q.Cleanup + q.SolutionSh
	for _, c := range q.Checks {
		all += c.Run + c.On
	}
	switch {
	case q.Driver != "kind":
		return "needs a VM driver"
	case q.FreshEnvironment:
		return "cannot be reset without a new cluster"
	case strings.Contains(all, "worker2"):
		return "needs two worker nodes"
	case workers >= 2 && (strings.Contains(q.ID, "one-pod-per-node") || strings.Contains(q.ID, "daemonset")):
		return "expects two worker nodes"
	case strings.Contains(all, "kubelet.service.d"):
		return "depends on the kubelet unit layout of kubedojo's nodes"
	case strings.Contains(all, "trivy"), strings.Contains(all, "kustomize "), strings.Contains(all, "etcdutl"):
		return "needs a tool that Killercoda images may not ship"
	case strings.Contains(all, "crictl inspect"), strings.Contains(all, "cri-containerd-"):
		return "depends on kubedojo's container runtime layout"
	}
	return ""
}

var (
	solveOn = regexp.MustCompile("(?m)^Solve this question on: `ssh \\{\\{host\\}\\}`\\s*\n")
	hostRef = regexp.MustCompile(" on `\\{\\{host\\}\\}`")
)

// text adapts task and solution markdown to Killercoda's host names.
func text(s string) string {
	s = solveOn.ReplaceAllString(s, "")
	s = hostRef.ReplaceAllString(s, "")
	r := strings.NewReplacer(
		"ssh {{host}}\n", "",
		"{{host}}-control-plane", "controlplane",
		"{{worker}}", "node01",
		"{{host}}", "controlplane",
	)
	return strings.TrimSpace(r.Replace(s)) + "\n"
}

// script adapts setup/solution/check commands.
func script(s string) string {
	r := strings.NewReplacer(
		"${KD_HOST}-control-plane", "controlplane",
		"${KD_HOST}-worker", "node01",
		"$KD_HOST-control-plane", "controlplane",
		"$KD_HOST-worker", "node01",
		"chown -R candidate:candidate", "true # chown",
		"chown candidate:candidate", "true # chown",
	)
	return r.Replace(s)
}

func shq(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// ere converts the Go regex syntax used in checks to POSIX ERE for grep -E.
func ere(re string) string {
	return strings.NewReplacer(`\d`, `[0-9]`, `\s`, `[[:space:]]`, `\S`, `[^[:space:]]`, `\w`, `[[:alnum:]_]`).Replace(re)
}

const verifyHead = `#!/bin/bash
# Generated by "kubedojo content export --format killercoda". Do not edit.
export KUBECONFIG=${KUBECONFIG:-/etc/kubernetes/admin.conf}
fail() { echo "FAILED: $1" >&2; exit 1; }
same_set() { [ "$(printf '%s\n' "$1" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//' | grep -v '^$' | sort)" = "$(printf '%s\n' "$2" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//' | grep -v '^$' | sort)" ]; }
trim() { printf '%s' "$1" | sed -e ':a' -e '$!{N;ba' -e '}' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//'; }
`

// verify renders all checks of a question as one bash script that exits 0
// only when every check passes.
func verify(q *catalog.Question) string {
	var b strings.Builder
	b.WriteString(verifyHead)
	for _, c := range q.Checks {
		cmd := script(checker.Command(c))
		if c.On == "worker" {
			cmd = "ssh -o StrictHostKeyChecking=no node01 " + shq(cmd)
		}
		title := shq(c.Title)
		fmt.Fprintf(&b, "\n# %s\nout=$( { %s\n} 2>/tmp/kd-stderr ); code=$?; out=$(trim \"$out\")\n", c.Title, cmd)
		if c.Type == "resource" && c.Absent {
			fmt.Fprintf(&b, "[ $code -ne 0 ] && grep -q NotFound /tmp/kd-stderr || fail %s\n", title)
			continue
		}
		want := 0
		e := c.Expect
		if e != nil && e.ExitCode != nil {
			want = *e.ExitCode
		}
		fmt.Fprintf(&b, "[ $code -eq %d ] || fail %s\n", want, title)
		if e == nil {
			continue
		}
		if e.Equals != nil {
			fmt.Fprintf(&b, "[ \"$out\" = %s ] || fail %s\n", shq(strings.TrimSpace(*e.Equals)), title)
		}
		if e.NotEquals != nil {
			fmt.Fprintf(&b, "[ \"$out\" != %s ] || fail %s\n", shq(strings.TrimSpace(*e.NotEquals)), title)
		}
		for _, s := range e.Contains {
			fmt.Fprintf(&b, "printf '%%s' \"$out\" | grep -qF -- %s || fail %s\n", shq(s), title)
		}
		for _, s := range e.NotContains {
			fmt.Fprintf(&b, "printf '%%s' \"$out\" | grep -qF -- %s && fail %s\n", shq(s), title)
		}
		if e.Matches != "" {
			fmt.Fprintf(&b, "printf '%%s' \"$out\" | grep -qE -- %s || fail %s\n", shq(ere(e.Matches)), title)
		}
		if len(e.OneOf) > 0 {
			fmt.Fprintf(&b, "printf '%%s\\n' %s | grep -qxF -- \"$out\" || fail %s\n", shq(strings.Join(e.OneOf, "\n")), title)
		}
		if len(e.SameLines) > 0 {
			fmt.Fprintf(&b, "same_set \"$out\" %s || fail %s\n", shq(strings.Join(e.SameLines, "\n")), title)
		}
		if len(e.SameItems) > 0 {
			fmt.Fprintf(&b, "same_set \"$(printf '%%s' \"$out\" | tr -s '[:space:]' '\\n')\" %s || fail %s\n", shq(strings.Join(e.SameItems, "\n")), title)
		}
		if e.Gte != nil {
			fmt.Fprintf(&b, "awk -v v=\"$out\" 'BEGIN{exit !(v+0 >= %v && v ~ /^-?[0-9.]+$/)}' || fail %s\n", *e.Gte, title)
		}
		if e.Lte != nil {
			fmt.Fprintf(&b, "awk -v v=\"$out\" 'BEGIN{exit !(v+0 <= %v && v ~ /^-?[0-9.]+$/)}' || fail %s\n", *e.Lte, title)
		}
		if e.NotEmpty {
			fmt.Fprintf(&b, "[ -n \"$out\" ] || fail %s\n", title)
		}
	}
	b.WriteString("\nexit 0\n")
	return b.String()
}

// Verify exposes the generated verification script (used by tests).
func Verify(q *catalog.Question) string { return verify(q) }

type step struct {
	Title  string `json:"title"`
	Text   string `json:"text"`
	Verify string `json:"verify"`
}

type page struct {
	Text       string `json:"text"`
	Background string `json:"background,omitempty"`
	Foreground string `json:"foreground,omitempty"`
}

type index struct {
	Title       string `json:"title"`
	Description string `json:"description"`
	Details     struct {
		Intro  page   `json:"intro"`
		Steps  []step `json:"steps"`
		Finish page   `json:"finish"`
	} `json:"details"`
	Backend struct {
		ImageID string `json:"imageid"`
	} `json:"backend"`
}

